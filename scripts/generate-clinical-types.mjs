import fs from 'node:fs';
import path from 'node:path';

const dir = path.resolve('config/clinical');
const read = name => JSON.parse(fs.readFileSync(path.join(dir, `${name}.schema.json`), 'utf8'));
const nameOf = name => name[0].toUpperCase() + name.slice(1);
function typeOf(schema) {
  if (schema.$ref) return nameOf(schema.$ref.split('/').at(-1));
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(x => JSON.stringify(x)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(type => typeOf({ ...schema, type })).join(' | ');
  if (schema.type === 'object') {
    if (!schema.properties) return `{ [key: string]: ${typeOf(schema.additionalProperties)} }`;
    return `{\n${Object.entries(schema.properties).map(([k, v]) => `  ${JSON.stringify(k)}${schema.required?.includes(k) ? '' : '?'}: ${typeOf(v)};`).join('\n')}\n}`;
  }
  if (schema.type === 'array') return `Array<${typeOf(schema.items)}>`;
  if (schema.type === 'integer') return 'number';
  if (['string', 'number', 'boolean', 'null'].includes(schema.type)) return schema.type;
  throw new Error('Unsupported schema type');
}
const definitions = Object.entries(read('common').$defs).map(([k, v]) => `export type ${nameOf(k)} = ${typeOf(v)};`);
for (const [name, type] of [['encounter', 'Encounter'], ['ai-output', 'AiOutput'], ['transcript', 'Transcript'], ['identity', 'Identity']]) {
  definitions.push(`export type ${type} = ${typeOf(read(name))};`);
}
const content = '// Generated by npm run clinical:types. Edit config/clinical/*.schema.json instead.\n\n' + definitions.join('\n\n') + '\n';
const output = path.resolve('src/shared/clinical/types.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) throw new Error('Clinical types are stale. Run npm run clinical:types.');
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, content);
}
