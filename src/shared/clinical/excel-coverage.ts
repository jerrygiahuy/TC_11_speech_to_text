/** Mọi khóa trường và cột của config phiếu: trường gốc, rồi (nếu là bảng lặp) từng cột `"<bảng>[].<cột>"`. */
export function excelKeys(config: CauHinhPhieu): string[] {
  return config.phan.flatMap(phan => phan.muc.flatMap(muc => muc.truong.flatMap(truong => [
    truong.khoa,
    ...(truong.cot ?? []).map(cot => `${truong.khoa}[].${cot.khoa}`),
  ])));
}
